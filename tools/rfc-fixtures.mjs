import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const manifest = new URL("../corpus/rfc8259.json", import.meta.url);
export const rfcFixtures = JSON.parse(readFileSync(manifest, "utf8")).cases;

// MoonBit source files are UTF-8. Derive a lone UTF-16 unit from its
// corresponding supplementary scalar for the raw invalid-Unicode fixtures.
export function moonString(value) {
  const pieces = [];
  let pending = "";
  const flush = () => {
    if (pending) pieces.push('"' + pending + '"');
    pending = "";
  };
  for (const char of value) {
    const code = char.codePointAt(0);
    if (code < 32 || code === 0xfeff || code === 0x2028 || code === 0x2029) {
      pending += "\\u{" + code.toString(16) + "}";
    } else if (code >= 0xd800 && code <= 0xdfff) {
      flush();
      const high = code < 0xdc00;
      const scalar = 0x10000 + (high ? (code - 0xd800) * 0x400 : code - 0xdc00);
      const index = Number(!high);
      pieces.push('"\\u{' + scalar.toString(16) + '}".unsafe_substring(start=' + index + ', end=' + (index + 1) + ')');
    } else {
      pending += char === '"' || char === "\\" ? "\\" + char : char;
    }
  }
  flush();
  return pieces.join(" + ") || '""';
}

function writeMoonTests() {
  const tested = [];
  for (const { id, class: kind, source, output, noEdits, error } of rfcFixtures) {
    const body = error
      ? ["  guard @json_repair.repair(" + moonString(source) + ") is Err(error) else {",
         '    fail("input selected for protective rejection was accepted")',
         "  }", "  assert_eq(error.kind.code(), " + moonString(error) + ")"]
      : ["  verify_rfc_value(", "    " + moonString(source) + ",", "    " + moonString(output) + ",",
         "    " + Boolean(noEdits) + ",", "  )"];
    tested.push(["///|", 'test "RFC 8259 ' + kind + " " + id + '" {', ...body, "}"].join("\n"));
  }
  const helpers = [
    "///|",
    "// Generated by node tools/rfc-fixtures.mjs from the pinned corpus. See corpus/README.md.",
    "fn verify_rfc_value(source : String, expected : String, no_edits : Bool) -> Unit raise {",
    "  let report = @json_repair.repair(source).unwrap()",
    "  assert_eq(report.json, expected)",
    "  assert_eq(report.edits.is_empty(), no_edits)",
    "  let strict = @json.parse(report.json[:], reject_duplicate_keys=true, preserve_number_repr=true)",
    "  assert_eq(strict.stringify(), report.value.stringify())",
    "  let repeated = @json_repair.repair(report.json).unwrap()",
    "  assert_eq(repeated.json, expected)",
    "  assert_true(repeated.edits.is_empty())",
    "}",
  ];
  writeFileSync(new URL("../rfc8259_test.mbt", import.meta.url), [helpers.join("\n"), ...tested].join("\n\n") + "\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) writeMoonTests();
