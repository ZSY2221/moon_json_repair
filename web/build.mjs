import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const options = { cwd: fileURLToPath(new URL("../", import.meta.url)), encoding: "utf8" };
const args = ["build", "cmd/playground", "--target", "js", "--release", "--deny-warn", "--output-json"];
let build = spawnSync("moon", args, options);
if (build.error?.code === "ENOENT") {
  const executable = process.platform === "win32" ? "moon.exe" : "moon";
  build = spawnSync(join(homedir(), ".moon", "bin", executable), args, options);
}
if (build.error) throw build.error;
if (build.stderr) process.stderr.write(build.stderr);
if (build.status !== 0) {
  if (build.stdout) process.stdout.write(build.stdout);
  process.exit(build.status ?? 1);
}

const artifact = build.stdout.split(/\r?\n/)
  .filter((line) => line.startsWith("{"))
  .map((line) => JSON.parse(line))
  .find((message) => message.$message_type === "artifact" && message.target_backend === "js" && message.package.endsWith("/cmd/playground"));
if (!artifact) throw new Error(`MoonBit did not report a JavaScript playground artifact.\n${build.stdout}`);

const engine = readFileSync(artifact.path, "utf8").replace(/\r\n/g, "\n");
const header = "// Generated by node web/build.mjs. Source is in cmd/playground and the MoonBit root package.\n";
writeFileSync(new URL("engine.js", import.meta.url), header + engine);
console.log("Built web/engine.js from the MoonBit playground package.");
